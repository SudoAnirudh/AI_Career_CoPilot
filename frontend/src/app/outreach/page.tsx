"use client";

import React, { useState, useEffect } from "react";
import { useApp, Message, Job, Contact } from "../../context/AppContext";
import { API_BASE_URL } from "../../config";
import { 
  Mail, 
  Send, 
  Edit3, 
  CheckSquare, 
  User,
  ExternalLink,
  FileDown
} from "lucide-react";
import confetti from "canvas-confetti";
import styles from "./page.module.css";

const OutreachPage: React.FC = () => {
  const { 
    messages, 
    jobs, 
    updateMessageDraft, 
    sendOutreach,
    getContactById,
    activeProfile
  } = useApp();

  const [selectedMsg, setSelectedMsg] = useState<Message | null>(null);
  const [contact, setContact] = useState<Contact | null>(null);
  const [editText, setEditText] = useState("");
  const [isEditing, setIsEditing] = useState(false);
  const [sendingId, setSendingId] = useState<string | null>(null);

  const getJobForMessage = (msg: Message): Job | undefined => {
    return jobs.find(j => j.id === msg.job_id);
  };

  const handleSelectMessage = (msg: Message) => {
    setSelectedMsg(msg);
    setEditText(msg.draft);
    setIsEditing(false);
  };

  // Fetch contact details when a message is selected
  useEffect(() => {
    if (selectedMsg) {
      getContactById(selectedMsg.contact_id)
        .then(setContact)
        .catch((err) => {
          console.error("Failed to load contact info:", err);
          setContact(null);
        });
    } else {
      setContact(null);
    }
  }, [selectedMsg, getContactById]);

  const handleSaveDraft = async () => {
    if (!selectedMsg) return;
    try {
      const updated = await updateMessageDraft(selectedMsg.id, editText);
      setSelectedMsg(updated);
      setIsEditing(false);
    } catch (e) {
      console.error(e);
      alert("Failed to save changes.");
    }
  };

  const handleSend = async (msg: Message) => {
    setSendingId(msg.id);
    try {
      const sent = await sendOutreach(msg.id);
      setSelectedMsg(sent);
      
      // Play premium canvas confetti
      confetti({
        particleCount: 120,
        spread: 70,
        origin: { y: 0.6 },
        colors: ["#8b5cf6", "#06b6d4", "#ec4899"]
      });

    } catch (e) {
      console.error(e);
      alert("Failed to send outreach.");
    } finally {
      setSendingId(null);
    }
  };

  // Helper to parse subject and body from the message draft
  const parseMessageText = (text: string) => {
    let subject = "";
    let body = text;

    const subjectMatch = text.match(/^Subject:\s*(.*)/i);
    if (subjectMatch) {
      subject = subjectMatch[1].trim();
      body = text.replace(/^Subject:.*\n?/i, "").trim();
    } else {
      // Generate standard fallback subject
      const job = selectedMsg ? getJobForMessage(selectedMsg) : null;
      subject = job ? `Application for ${job.title} - ${job.company}` : "Outreach Inquiry";
    }

    return { subject, body };
  };

  // Open Gmail compose in a new tab with pre-filled fields
  const handleOpenInGmail = () => {
    if (!selectedMsg) return;
    const { subject, body } = parseMessageText(editText || selectedMsg.draft);
    const toEmail = contact?.email || `hr@${getJobForMessage(selectedMsg)?.company?.toLowerCase().replace(/\s+/g, "") || "company"}.com`;
    
    const gmailUrl = `https://mail.google.com/mail/?view=cm&fs=1&to=${encodeURIComponent(toEmail)}&su=${encodeURIComponent(subject)}&body=${encodeURIComponent(body)}`;
    window.open(gmailUrl, "_blank");
  };

  // Download active resume PDF from the server
  const handleDownloadResume = () => {
    if (activeProfile?.resume_url) {
      const resumeUrl = `${API_BASE_URL}${activeProfile.resume_url}`;
      window.open(resumeUrl, "_blank");
    } else {
      alert("No active resume uploaded. Please go to Settings to upload your resume.");
    }
  };

  return (
    <div className={styles.container}>
      <div className={styles.pageHeader}>
        <div>
          <h1>Outreach Center</h1>
          <p>Review, edit, and send highly personalized cold messages generated by the Nvidia NIM agents.</p>
        </div>
      </div>

      <div className={styles.mainLayout}>
        {/* Left Side: Messages Queue */}
        <div className={styles.queuePanel}>
          <h3 className={styles.panelTitle}>Messages Queue ({messages.length})</h3>
          
          <div className={styles.messagesList}>
            {messages.length === 0 ? (
              <div className={styles.emptyQueue}>
                <Mail size={44} className={styles.emptyIcon} />
                <h4>No outreach drafts created yet</h4>
                <p>Go to the Opportunities page, click on a job, and click "Email Draft" to start pitching.</p>
              </div>
            ) : (
              messages.map((msg) => {
                const job = getJobForMessage(msg);
                const isSelected = selectedMsg?.id === msg.id;

                return (
                  <div 
                    key={msg.id} 
                    className={`${styles.msgItem} ${isSelected ? styles.selectedItem : ""}`}
                    onClick={() => handleSelectMessage(msg)}
                  >
                    <div className={styles.msgHeader}>
                      <span className={styles.msgType}>
                        {msg.type === "cold_email" ? "Cold Email" : "LinkedIn Pitch"}
                      </span>
                      <span className={`${styles.statusBadge} ${styles[msg.status]}`}>
                        {msg.status}
                      </span>
                    </div>

                    <h4 className={styles.msgTarget}>
                      To Recruiter &bull; {job?.company || "Unknown Company"}
                    </h4>
                    
                    <p className={styles.jobHeading}>{job?.title}</p>
                    <p className={styles.snippetText}>{msg.draft}</p>
                  </div>
                );
              })
            )}
          </div>
        </div>

        {/* Right Side: Message Editor */}
        <div className={styles.editorPanel}>
          {selectedMsg ? (
            <div className={styles.editorContainer}>
              <div className={styles.editorHeader}>
                <div>
                  <div className={styles.recruiterProfile}>
                    <User size={16} className={styles.avatarIcon} />
                    <span>Decision Maker for {getJobForMessage(selectedMsg)?.company}</span>
                  </div>
                  <h2>Outreach Draft Details</h2>
                </div>

                <div className={styles.headerActions} style={{ display: "flex", gap: "0.5rem" }}>
                  {activeProfile && (
                    <button 
                      className="btn-secondary"
                      onClick={handleDownloadResume}
                      style={{ padding: "0.45rem 0.9rem", fontSize: "0.8rem" }}
                      title="Download/view your active resume PDF"
                    >
                      <FileDown size={14} />
                      <span>My Resume</span>
                    </button>
                  )}
                  {selectedMsg.status === "draft" && (
                    <button 
                      className="btn-secondary"
                      onClick={() => {
                        if (isEditing) handleSaveDraft();
                        else setIsEditing(true);
                      }}
                      style={{ padding: "0.45rem 0.9rem", fontSize: "0.8rem" }}
                    >
                      <Edit3 size={14} />
                      <span>{isEditing ? "Save Draft" : "Edit Draft"}</span>
                    </button>
                  )}
                </div>
              </div>

              {/* Recruiter info card */}
              <div className={styles.recruiterCard}>
                <div className={styles.recruiterRow}>
                  <div>
                    <span className={styles.recruiterName}>
                      {contact?.name || "Hiring Manager"}
                    </span>
                    <span className={styles.recruiterTitle}>
                      {contact?.title ? ` &bull; ${contact.title}` : ""}
                    </span>
                  </div>
                  {contact?.linkedin_url && (
                    <a 
                      href={contact.linkedin_url} 
                      target="_blank" 
                      rel="noopener noreferrer"
                      className="text-primary flex items-center gap-1"
                      style={{ fontSize: "0.8rem", textDecoration: "underline" }}
                    >
                      LinkedIn <ExternalLink size={12} />
                    </a>
                  )}
                </div>
                <div>
                  <span style={{ fontSize: "0.75rem", color: "var(--text-muted)", marginRight: "0.5rem" }}>Email:</span>
                  <span className={styles.recruiterEmail}>
                    {contact?.email || `hr@${getJobForMessage(selectedMsg)?.company?.toLowerCase().replace(/\s+/g, "") || "company"}.com`}
                  </span>
                </div>
              </div>

              {/* Parsed Subject line display (read-only when not editing) */}
              {!isEditing && (
                <div className={styles.subjectBlock}>
                  <span className={styles.subjectLabel}>Subject</span>
                  <span className={styles.subjectText}>
                    {parseMessageText(selectedMsg.draft).subject}
                  </span>
                </div>
              )}

              {/* Text Area / Render */}
              <div className={styles.bodySection}>
                {isEditing ? (
                  <textarea 
                    className={`${styles.editorInput} form-input`}
                    rows={12}
                    value={editText}
                    onChange={(e) => setEditText(e.target.value)}
                  />
                ) : (
                  <div className={styles.msgViewText}>
                    {parseMessageText(selectedMsg.draft).body}
                  </div>
                )}
              </div>

              {/* Footer controls */}
              <div className={styles.editorFooter}>
                <div className={styles.metaInfo}>
                  <span>Created: {new Date(selectedMsg.created_at).toLocaleDateString()}</span>
                  {selectedMsg.sent_at && (
                    <span>Sent: {new Date(selectedMsg.sent_at).toLocaleDateString()}</span>
                  )}
                </div>

                <div className={styles.sendGroup} style={{ gap: "0.75rem" }}>
                  {selectedMsg.status === "draft" && (
                    <>
                      <button 
                        className={`btn-secondary ${styles.gmailBtn}`}
                        onClick={handleOpenInGmail}
                      >
                        <Mail size={16} />
                        <span>Open in Gmail</span>
                      </button>
                      <button 
                        className="btn-primary animate-pulse"
                        onClick={() => handleSend(selectedMsg)}
                        disabled={sendingId === selectedMsg.id}
                      >
                        <Send size={16} />
                        <span>{sendingId === selectedMsg.id ? "Sending..." : "Send via App"}</span>
                      </button>
                    </>
                  )}
                  {selectedMsg.status === "sent" && (
                    <div className={styles.sentConfirmation}>
                      <CheckSquare size={16} />
                      <span>Message successfully sent!</span>
                    </div>
                  )}
                </div>
              </div>
            </div>
          ) : (
            <div className={styles.noEditorSelection}>
              <Mail size={54} className={styles.sparkleIcon} />
              <h3>Select a message draft</h3>
              <p>Choose an outreach item from the left queue to review, custom compile, or launch the automated delivery sequence.</p>
            </div>
          )}
        </div>
      </div>
    </div>
  );
};

export default OutreachPage;
